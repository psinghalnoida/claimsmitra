    function fetchCompany() {
        $.ajax({
            type: "POST",
            url: "<?php echo base_url('companynames'); ?>",
            dataType: "json",
            data: {
                companyid,companyid
            },
            success: function(response) {
                console.log(response);
                if (response.status === 200) {
                    $('#companyDropdown').empty();
                    var companyData = response.data.companies;
                    var departmentData = response.data.departments;
                    $('#companyDropdown').append(`<option value="0" title="Individual">
                                           Individual
                                          </option>`);
                    companyData.forEach(function(company) {
                        var truncatedCompanyName = truncateText(company.companyName, 20);
                        var optionCompany = `<option value="${company.cid}" title="${company.companyName}">
                                            ${truncatedCompanyName}
                                          </option>`;
