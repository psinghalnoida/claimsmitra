    function encrypturl(pageurl, companyid, departmentid) {
        $.ajax({
            url: 'encryptdata', // Path to the PHP script
            type: 'POST',   
            data: {
                defaultcompany: companyid,
                defaultdepartment: departmentid,
                usertype: user_role
            },
            dataType: 'json', // Expecting JSON response
            success: function(response) {
                // encryptedurl = response.data;
                var url = `${pageurl}?data=${encodeURIComponent(response.data)}`;
                // var url = 'dashboard' + '?' + $.param({data: response.data});  
                history.pushState(null, '', url);
                incomingcases.ajax.reload();
                completedcase.ajax.reload();
                quicksurveycases.ajax.reload();
            },
            error: function(xhr, status, error) {
                console.error("AJAX Error:", error);
            }
        });
    }



    function redirectToController(pageurl, company, department, usertype) {
        $.ajax({
            url: '<?= base_url("encryptdata") ?>', // Correct endpoint for encryption
            type: 'POST',
            data: {
                defaultcompany: company,
                defaultdepartment: department,
                usertype: usertype
            },
            dataType: 'json', // Expecting a JSON response
            success: function(response) {
                if (response.data) {
                    // Construct the URL with encrypted data
                    let url = `${pageurl}?data=${encodeURIComponent(response.data)}`;
                    // Redirect to the constructed URL
                    window.location.href = url;
                } else {
                    console.error("Error: No encrypted data received.");
                }
            },
            error: function(xhr, status, error) {
                console.error("AJAX Error:", error);
            }
        });
    }

    function truncateText(text, maxLength) {
        if (text.length > maxLength) {
            return text.substring(0, maxLength) + '...';
        }

        return text;
    }

